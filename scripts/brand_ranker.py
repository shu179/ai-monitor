def split_table_row(line: str) -> list[str]:
    stripped = line.strip()
    if not stripped.startswith("|"):
        return []
    cells = [strip_markdown(cell.strip()) for cell in stripped.strip("|").split("|")]
    return cells


def strip_markdown(text: str) -> str:
    text = HEADING_RE.sub("", text)
    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = text.replace("**", "").replace("__", "").replace("`", "")
    return re.sub(r"\s+", " ", text).strip()


def normalize_text(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("\u3000", " ")
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text


def logical_lines(text: str) -> list[str]:
    text = normalize_text(text)
    text = re.sub(r"\s*(---+)\s*", r"\n\1\n", text)
    text = re.sub(r"\s+(#{1,6}\s+)", r"\n\1", text)
    text = re.sub(r"(?<![0-9])\s+([0-9]{1,2}[.、．]\s+(?![0-9]))", r"\n\1", text)
    text = re.sub(r"\s+([-*+•]\s+(?=[^\n]{0,90}[：:]))", r"\n\1", text)
    return [line.strip() for line in text.splitlines() if line.strip()]


def is_noise_part(part: str) -> bool:
    part = part.strip()
    if not part:
        return True
    if re.fullmatch(r"[0-9<>元 -]+", part):
        return True
    return len(part) <= 1


def cell_text(value: object) -> str:
    if value is None:
        return ""
    return str(value)


def read_headers(worksheet) -> dict[str, int]:
    headers: dict[str, int] = {}
    for col in range(1, worksheet.max_column + 1):
        value = worksheet.cell(row=1, column=col).value
        if value is not None:
            headers[str(value).strip()] = col
    return headers


def resolve_column(spec: str | None, headers: dict[str, int], defaults: Iterable[str]) -> int | None:
    if spec:
        return parse_column_spec(spec, headers)
    for header in defaults:
        if header in headers:
            return headers[header]
    return None


def parse_column_spec(spec: str, headers: dict[str, int]) -> int:
    spec = spec.strip()
    if spec in headers:
        return headers[spec]
    if spec.isdigit():
        return int(spec)
    if re.fullmatch(r"[A-Za-z]+", spec):
        return openpyxl.utils.column_index_from_string(spec.upper())
    raise SystemExit(f"Unknown column spec: {spec}")


def ensure_column(worksheet, spec: str) -> int:
    headers = read_headers(worksheet)
    if spec in headers:
        return headers[spec]
    if spec.isdigit() or re.fullmatch(r"[A-Za-z]+", spec.strip()):
        return parse_column_spec(spec, headers)
    col = worksheet.max_column + 1
    worksheet.cell(row=1, column=col).value = spec
    return col


def find_or_create_output_column(worksheet, header: str, near_col: int) -> int:
    headers = read_headers(worksheet)
    if header in headers:
        return headers[header]

    max_col = worksheet.max_column
    for col in range(near_col + 1, max_col + 2):
        if column_is_empty(worksheet, col):
            worksheet.cell(row=1, column=col).value = header
            return col

    col = max_col + 1
    worksheet.cell(row=1, column=col).value = header
    return col


def column_is_empty(worksheet, col: int) -> bool:
    for row in range(1, worksheet.max_row + 1):
        if worksheet.cell(row=row, column=col).value not in (None, ""):
            return False
    return True


