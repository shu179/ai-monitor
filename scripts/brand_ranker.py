def dedupe_keep_order(values: Iterable[str]) -> list[str]:
    seen = set()
    out = []
    for value in values:
        if value in seen:
            continue
        seen.add(value)
        out.append(value)
    return out


def clip(text: str, limit: int = 260) -> str:
    text = strip_markdown(text).replace("\n", " ")
    return text if len(text) <= limit else text[: limit - 1] + "…"


